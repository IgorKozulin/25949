#include <stdio.h>
#include <stdlib.h>
#include <unistd.h>
#include <sys/types.h>
#include <sys/wait.h>

int main(int argc, char *argv[]) {
    if (argc < 2) {
        fprintf(stderr, "Использование: %s <имя_файла>\n", argv[0]);
        return 1;
    }

    printf("[РОДИТЕЛЬ] Старт программы. Мой PID: %d\n", getpid());

    // 1. Создаем дочерний процесс
    pid_t pid = fork();

    if (pid < 0) {
        // Ошибка при создании процесса
        perror("Ошибка fork");
        return 1;
    }

    if (pid == 0) {
        // ------------------------------------------------------
        // КОД ДОЧЕРНЕГО ПРОЦЕССА (pid == 0)
        // ------------------------------------------------------
        printf("[РЕБЕНОК] Я родился! Мой PID: %d. Сейчас запущу cat...\n", getpid());
        fflush(stdout);

        // Заменяем тело дочернего процесса утилитой cat
        // Первый аргумент "cat" - что ищем в PATH
        // Второй аргумент "cat" - это argv[0] для самой программы cat
        execlp("cat", "cat", argv[1], NULL);

        // Этот код выполнится ТОЛЬКО если execlp провалился!
        perror("Ошибка execlp");
        exit(EXIT_FAILURE);
    } else {
        // ------------------------------------------------------
        // КОД РОДИТЕЛЬСКОГО ПРОЦЕССА (pid > 0, где pid - это PID ребенка)
        // ------------------------------------------------------
        printf("[РОДИТЕЛЬ] Я создал ребенка с PID: %d\n", pid);
        printf("[РОДИТЕЛЬ] Печатаю промежуточный текст, пока ребенок работает...\n");
        fflush(stdout);

        int status;
        printf("[РОДИТЕЛЬ] Жду завершения дочернего процесса через waitpid()...\n");
        fflush(stdout);

        // Блокируем родителя до тех пор, пока ребенок не завершится
        waitpid(pid, &status, 0);

        // Анализируем, как завершился ребенок
        if (WIFEXITED(status)) {
            printf("\n[РОДИТЕЛЬ] Ребенок успешно завершился с кодом возврата: %d\n", WEXITSTATUS(status));
        } else {
            printf("\n[РОДИТЕЛЬ] Ребенок завершился нештатно!\n");
        }

        // Финальная строка строго ПОСЛЕ завершения потомка (требование задания)
        printf("[РОДИТЕЛЬ] >>> ЭТО ПОСЛЕДНЯЯ СТРОКА РОДИТЕЛЯ ПОСЛЕ ЗАВЕРШЕНИЯ РЕБЕНКА <<<\n");
    }

    return 0;
}
